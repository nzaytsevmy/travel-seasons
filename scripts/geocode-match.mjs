// Совпадает ли город, который вернул геокодер, с тем, который просили.
//
// ⛔ Зачем отдельная функция и тест к ней. До 08.09.2026 геокодер в
// fetch-climate-normals.mjs брал первый результат с нужным кодом страны:
// `(j.results || []).find((r) => r.country_code === p.cc)`. Проверялась страна,
// а не город. На запрос «Panaji» единственным индийским совпадением оказалась
// деревня Panāji Muwara в Гуджарате, и десять лет норм Ахмадабада уехали в
// данные под подписью «Замер по городу Панаджи (Гоа)» — на 25 живых страниц
// Гоа, включая списки вещей. Октябрь показывал 30 мм и «сухой сезон» при норме
// метеослужбы Индии 124,8 мм.
//
// Правило: имя должно совпасть с точностью до диакритики, регистра, дефисов и
// пары букв в написании. Лишнее слово в названии («Panaji» → «Panaji Muwara»)
// совпадением не считается — это другой населённый пункт.

const нормализовать = (s) => (s || '')
  .normalize('NFD').replace(/[̀-ͯ]/g, '')   // diacritics: Panāji → Panaji
  .toLowerCase()
  .replace(/[^a-z0-9 ]/g, ' ')                        // дефисы и апострофы не различают города
  .replace(/\s+/g, ' ')
  .trim();

// Расстояние Левенштейна: терпит «Puerto Montt» → «Port Montt» и
// «Petropavlovsk-Kamchatsky» → «Petropavlovsk-Kamchatskiy», то есть разное
// написание одного города.
function расстояние(a, b) {
  const prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let diag = prev[0];
    prev[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const tmp = prev[j];
      prev[j] = Math.min(prev[j] + 1, prev[j - 1] + 1, diag + (a[i - 1] === b[j - 1] ? 0 : 1));
      diag = tmp;
    }
  }
  return prev[b.length];
}

export function этотЖеГород(запрос, ответ) {
  const a = нормализовать(запрос), b = нормализовать(ответ);
  if (!a || !b) return false;
  if (a === b) return true;
  // Разное число слов — почти всегда другой населённый пункт с похожим корнем.
  if (a.split(' ').length !== b.split(' ').length) return false;
  return расстояние(a, b) <= 3;
}
