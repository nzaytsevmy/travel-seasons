// Время последнего изменения у файлов страниц — из карты сайта, а не из момента
// сборки.
//
// Зачем. Сервер отвечает роботу «страница не менялась» (код 304), только если
// время файла старше того, что робот запомнил. Сборка создаёт все 2 466 файлов
// заново, значит после каждой выкладки у всех время новое — и робот качает весь
// сайт целиком.
//
// Замер по журналам сервера за 19–27.08.2026:
//   Googlebot   2 203 полных ответа, «не изменилось» — ни одного
//   YandexBot   3 324 полных ответа, «не изменилось» — ни одного
//   повторных заходов на уже виденное: 57% у Google, 70% у Яндекса
//   чаще всего Google перепроверял страницу про печеньки — 54 раза за 8 дней
// За те же 8 дней Google открыл десять августовских статей ОДИН раз, Яндекс — 96.
//
// ⛔ Сравнение по содержимому (--checksum) эту задачу НЕ решает: файл перестаёт
//    передаваться, но время ему всё равно проставляется свежее. Проверено опытом
//    27.08.2026. Единственное, что помогает, — проставить верное время ДО заливки:
//    тогда rsync перенесёт его как есть, и неизменная страница сохранит своё.
//
// Дату берём из карты сайта: она уже считается по настоящим изменениям —
// у страниц про страну по данным этой страны, у статей по их правкам.
//
// Запуск: node scripts/set-page-mtimes.mjs [каталог сборки]

import { readFileSync, utimesSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const КАТАЛОГ = process.argv[2] || 'dist';
const КАРТА = join(КАТАЛОГ, 'sitemap-0.xml');

if (!existsSync(КАРТА)) {
  console.log('карта сайта не найдена — время страниц оставлено как есть');
  process.exit(0);
}

const xml = readFileSync(КАРТА, 'utf8');
let поставлено = 0, пропущено = 0;

for (const m of xml.matchAll(/<loc>https:\/\/traveltribe\.ru([^<]*)<\/loc><lastmod>([^<]*)<\/lastmod>/g)) {
  const путь = m[1];
  const время = new Date(m[2]);
  if (Number.isNaN(время.valueOf())) { пропущено++; continue; }

  const файл = путь.endsWith('/')
    ? join(КАТАЛОГ, путь, 'index.html')
    : join(КАТАЛОГ, путь);
  if (!existsSync(файл)) { пропущено++; continue; }

  // Время доступа не важно, но utimes требует оба — ставим то же самое.
  utimesSync(файл, время, время);
  поставлено++;
}

console.log(`время страниц: проставлено ${поставлено}, пропущено ${пропущено}`);
