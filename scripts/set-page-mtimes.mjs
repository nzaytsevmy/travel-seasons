// Время последнего изменения у файлов страниц — из карты сайта, а не из момента
// сборки.
//
// Зачем. Сервер отвечает роботу «страница не менялась» (код 304), только если
// время файла старше того, что робот запомнил. Сборка создаёт все 2 466 файлов
// заново, значит после каждой выкладки у всех время новое — и робот качает весь
// сайт целиком.
//
// Замер по журналам сервера за 19–27.08.2026:
//   Googlebot   2 203 полных ответа, «не изменилось» — ни одного
//   YandexBot   3 324 полных ответа, «не изменилось» — ни одного
//   повторных заходов на уже виденное: 57% у Google, 70% у Яндекса
//   чаще всего Google перепроверял страницу про печеньки — 54 раза за 8 дней
// За те же 8 дней Google открыл десять августовских статей ОДИН раз, Яндекс — 96.
//
// ⛔ Сравнение по содержимому (--checksum) эту задачу НЕ решает: файл перестаёт
//    передаваться, но время ему всё равно проставляется свежее. Проверено опытом
//    27.08.2026. Единственное, что помогает, — проставить верное время ДО заливки:
//    тогда rsync перенесёт его как есть, и неизменная страница сохранит своё.
//
// Дату берём из карты сайта: она уже считается по настоящим изменениям —
// у страниц про страну по данным этой страны, у статей по их правкам.
//
// Запуск: node scripts/set-page-mtimes.mjs [каталог сборки]

import { readFileSync, utimesSync, existsSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

/** Все собранные страницы каталога. */
function все_страницы(корень) {
  const out = [];
  const обойти = (д) => {
    for (const имя of readdirSync(д, { withFileTypes: true })) {
      const п = join(д, имя.name);
      if (имя.isDirectory()) обойти(п);
      else if (имя.name === 'index.html') out.push(п);
    }
  };
  обойти(корень);
  return out;
}

const КАТАЛОГ = process.argv[2] || 'dist';
const КАРТА = join(КАТАЛОГ, 'sitemap-0.xml');

if (!existsSync(КАРТА)) {
  console.log('карта сайта не найдена — время страниц оставлено как есть');
  process.exit(0);
}

const xml = readFileSync(КАРТА, 'utf8');
let поставлено = 0, пропущено = 0;
const изКарты = new Set();

for (const m of xml.matchAll(/<loc>https:\/\/traveltribe\.ru([^<]*)<\/loc><lastmod>([^<]*)<\/lastmod>/g)) {
  const путь = m[1];
  const время = new Date(m[2]);
  if (Number.isNaN(время.valueOf())) { пропущено++; continue; }

  const файл = путь.endsWith('/')
    ? join(КАТАЛОГ, путь, 'index.html')
    : join(КАТАЛОГ, путь);
  if (!existsSync(файл)) { пропущено++; continue; }

  // Время доступа не важно, но utimes требует оба — ставим то же самое.
  utimesSync(файл, время, время);
  изКарты.add(путь);
  поставлено++;
}

// ⛔ Страницы вне карты сайта роботы всё равно обходят: за 19–27.08.2026 на них
//    пришлось 346 заходов из 5 070, причём 84 — на две юридические страницы,
//    которые не менялись с 10 июля. Без даты они остаются с временем сборки и
//    перекачиваются каждый раз. Берём дату последней правки их исходника.
const исходник = (путь) => {
  const голый = путь.replace(/^\//, '').replace(/\/$/, '');
  return [
    `src/pages/${голый}.astro`,
    `src/pages/${голый}/index.astro`,
  ];
};

// ⛔ Дочинка 29.08.2026. У страниц из шаблонов с параметром (метки блога,
// программные пути) прямого исходника нет: /blog/tag/2026/ рождается из
// src/pages/blog/tag/[tag].astro, и подстановка выше его не находила. Тогда все
// такие страницы — 455 штук — скопом получали запасную «общую дату данных», то
// есть полночь дня последней правки фактуры. Две беды сразу: ночной прогон
// видит эту полночь в будущем и гейт краснеет, а главное — сотни не менявшихся
// страниц каждый день данных выглядят для роботов «обновлёнными сегодня».
// Это та же ловушка «общая дата съедает обход», уже пойманная на карте сайта.
// Решение: идти по сегментам пути, допуская на каждом шаге каталог или файл
// вида [параметр], и брать git-дату найденного шаблона.
const шаблонныйИсходник = (путь) => {
  const сегменты = путь.replace(/^\//, '').replace(/\/$/, '').split('/');
  let каталоги = ['src/pages'];
  for (let i = 0; i < сегменты.length; i++) {
    const последний = i === сегменты.length - 1;
    const следующие = [];
    for (const к of каталоги) {
      if (!existsSync(к)) continue;
      const записи = readdirSync(к, { withFileTypes: true });
      for (const з of записи) {
        const динамическая = /^\[.+\]/.test(з.name);
        if (последний) {
          const имяФайла = з.name.replace(/\.astro$/, '');
          const подходит = з.isFile() && з.name.endsWith('.astro') &&
            (имяФайла === сегменты[i] || /^\[.+\]$/.test(имяФайла));
          if (подходит) следующие.push(`${к}/${з.name}`);
          if (з.isDirectory() && (з.name === сегменты[i] || динамическая) &&
              existsSync(`${к}/${з.name}/index.astro`)) {
            следующие.push(`${к}/${з.name}/index.astro`);
          }
        } else if (з.isDirectory() && (з.name === сегменты[i] || динамическая)) {
          следующие.push(`${к}/${з.name}`);
        }
      }
    }
    каталоги = следующие;
    if (!каталоги.length) return [];
  }
  return каталоги.filter((f) => f.endsWith('.astro'));
};

const датаФайла = (кандидаты) => {
  for (const f of кандидаты) {
    if (!existsSync(f)) continue;
    try {
      const d = execFileSync('git', ['log', '-1', '--format=%cI', '--', f],
        { encoding: 'utf8' }).trim();
      if (d) return new Date(d);
    } catch { /* истории нет — пропускаем */ }
  }
  return null;
};

// Общая дата данных — запасной вариант для тех, чей исходник не нашёлся.
let общая = null;
try {
  общая = new Date(JSON.parse(readFileSync('src/data/freshness.generated.json', 'utf8')).dataUpdated + 'T00:00:00Z');
} catch { /* нет файла — оставим как есть */ }

let вне = 0;
for (const файл of все_страницы(КАТАЛОГ)) {
  const путь = файл.replace(КАТАЛОГ, '').replace(/index\.html$/, '');
  if (изКарты.has(путь)) continue;
  const когда = датаФайла(исходник(путь)) || датаФайла(шаблонныйИсходник(путь)) || общая;
  if (!когда || Number.isNaN(когда.valueOf())) continue;
  utimesSync(файл, когда, когда);
  вне++;
}

console.log(`время страниц: из карты ${поставлено}, по исходнику ${вне}, пропущено ${пропущено}`);
