/**
 * Вырезает разметку и отдаёт видимый человеку текст.
 *
 * ⛔ Наивные выражения `<script.*?</script>` и `<[^>]+>` разбор не проходят:
 *    настоящая разметка пишет закрывающий тег с пробелом (`</script >`),
 *    прячет текст в комментариях и держит «>» внутри значений атрибутов.
 *    Проверка безопасности 27.08.2026 назвала это четырьмя важными
 *    замечаниями; для нас важнее второе — такой разбор МЕРИТ НЕ ТО:
 *    содержимое скрипта или комментария утекает в «видимый текст» и даёт
 *    ложную тревогу, а текст за атрибутом с «>» теряется и даёт пропуск.
 *
 *    Закрывающий тег вдобавок может нести мусор после имени — разборщики
 *    принимают `</script foo>` и `</script\t\n bar>` как закрытие. Поэтому
 *    после имени тега стоит `[^>]*`, а не `\s*`.
 *
 *    Порядок обязателен: сначала комментарии, потом парные блоки с терпимым
 *    закрывающим тегом, и только потом одиночные теги — с учётом кавычек,
 *    чтобы «>» внутри значения атрибута не обрывал тег раньше времени.
 */
export function видимыйТекст(html: string, замена = ' '): string {
  return html
    .replace(/<!--[\s\S]*?-->/g, замена)
    .replace(/<script\b[\s\S]*?<\/script\b[^>]*>/gi, замена)
    .replace(/<style\b[\s\S]*?<\/style\b[^>]*>/gi, замена)
    .replace(/<noscript\b[\s\S]*?<\/noscript\b[^>]*>/gi, замена)
    .replace(/<(code|pre)\b[\s\S]*?<\/\1\b[^>]*>/gi, замена)
    .replace(/<[a-zA-Z\/!][^>"']*(?:"[^"]*"[^>"']*|'[^']*'[^>"']*)*>/g, замена)
    .replace(/&nbsp;|&#160;/gi, ' ')
    .replace(/&[a-z]+;|&#\d+;/gi, замена);
}
