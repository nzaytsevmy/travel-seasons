// Неразрывные пробелы: предлог не висит, число не отрывается, тире не начинает строку.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { typo } from '../src/utils/typo.js';
const N = ' ';

test('короткий предлог и союз склеиваются со следующим словом', () => {
  assert.equal(typo('с ноября по апрель и в мае'), `с${N}ноября по${N}апрель и${N}в${N}мае`);
});
test('число не отрывается от единицы и от слова', () => {
  assert.equal(typo('вода 24–28 °C, в пути 6 часов 20 минут'), `вода 24–${WJ}28${N}°C, в${N}пути 6${N}часов 20${N}минут`);
});
test('тире не начинает строку', () => {
  assert.equal(typo('Маскат — север'), `Маскат${N}— север`);
});
test('заглавная буква в начале предложения тоже считается', () => {
  assert.equal(typo('В Салале в хариф'), `В${N}Салале в${N}хариф`);
});
test('пустое и не строка — как есть', () => {
  assert.equal(typo(''), ''); assert.equal(typo(undefined), undefined);
});

// Замечания Никиты 10.09.2026 на странице Турции: «(макс 90/180)» уезжало «90/180)» одно
// на новую строку, «(~май-июнь)» отрывалось от «плавающая дата». Короткая скобка держится
// за предыдущее слово и не рвётся внутри; диапазон и дробь не рвутся по знаку.
const WJ = '\u2060';
test('короткая скобка не рвётся внутри и держится за короткий кусок перед ней', () => {
  assert.equal(typo('бесплатно, 60 дней (макс 90/180)'), `бесплатно, 60${N}дней${N}(макс${N}90/${WJ}180)`);
  assert.equal(typo('плавающая дата (~май-июнь)'), `плавающая дата${N}(~май-${WJ}июнь)`);
  // 10.09.2026: косая между буквами тоже давала разрыв — «гепатит А/» на одной строке, «Б)» на другой
  assert.equal(typo('набор (АДС, гепатит А/Б)'), `набор${N}(АДС,${N}гепатит${N}А/${WJ}Б)`);
  assert.equal(typo('без визы (до 90/год)'), `без${N}визы${N}(до${N}90/${WJ}год)`);
});
test('диапазон чисел — короткое тире без разрыва, телефон и дата не трогаются', () => {
  assert.equal(typo('около 27-30 мая'), `около 27–${WJ}30${N}мая`);
  assert.equal(typo('+90-312-419-21-22'), '+90-312-419-21-22');
  assert.equal(typo('2026-09-10'), '2026-09-10');
});
test('скобка не клеится, если вместе с куском перед ней выходит длиннее 24 знаков', () => {
  // «для Каппадокии (тропы каменистые)» — 33 знака: склейка давала на телефоне кусок шире строки
  assert.equal(typo('обувь для Каппадокии (тропы каменистые)'), `обувь для${N}Каппадокии (тропы${N}каменистые)`);
  assert.equal(typo('Курбан-Байрам (Eid al-Adha)'), `Курбан-Байрам (Eid${N}al-${WJ}Adha)`);
});
test('длинная скобка не склеивается целиком', () => {
  // внутри работают только обычные правила — предлог держится за следующее слово
  assert.equal(typo('сезон (в горах Каппадокии бывает снег до апреля)'), `сезон (в${N}горах Каппадокии бывает снег до${N}апреля)`);
});

test('повторный прогон ничего не меняет', () => {
  for (const s of ['бесплатно, 60 дней (макс 90/180)', 'плавающая дата (~май-июнь)', 'около 27-30 мая', 'с ноября по апрель и в мае', 'Маскат — север']) {
    assert.equal(typo(typo(s)), typo(s), s);
  }
});

import { typoHtml } from '../tools/typo-dist.mjs';
test('типограф сайта трогает только текст между тегами', () => {
  const html = '<title>Виза в Турцию</title><p data-x="в дом">Виза в <a href="/visa/">Турцию</a> (макс 90/180)</p><script>var a = "в дом";</script><pre>x - y (a b)</pre>';
  const out = typoHtml(html);
  assert.ok(out.includes('<title>Виза в Турцию</title>'), 'title не трогаем');
  assert.ok(out.includes('data-x="в дом"'), 'атрибуты не трогаем');
  assert.ok(out.includes('var a = "в дом";') && out.includes('<pre>x - y (a b)</pre>'), 'скрипт и код не трогаем');
  assert.ok(out.includes(`Виза в${N}<a href="/visa/">`), 'предлог перед ссылкой держится за неё');
  assert.ok(out.includes(`${N}(макс${N}90/${WJ}180)`), 'скобка держится за «Турцию» и не рвётся внутри');
  assert.equal(typoHtml(out), out, 'повторный прогон ничего не меняет');
});

// 10.09.2026: повторный проход по сборке менял ещё 32 страницы — типограф недоклеивал
// за один проход. Косые шли через одну («1/3/5/10»: соседние совпадения перекрывались),
// короткое тире внутри скобки оставалось местом разрыва («(-10–15%)»).
test('цепочка через косую и тире в скобке склеиваются за один проход', () => {
  assert.equal(typo('3/6/12 мес'), `3/${WJ}6/${WJ}12${N}мес`);
  assert.equal(typo('Пакеты 1/3/5/10/20 ГБ'), `Пакеты 1/${WJ}3/${WJ}5/${WJ}10/${WJ}20${N}ГБ`);
  assert.equal(typo('ниже на (-10–15%)'), `ниже на${N}(-${WJ}10–${WJ}15%)`);
  for (const s of ['3/6/12 мес', 'ниже (-10–15%)', 'и не в этом дело', 'а и в то же время']) assert.equal(typo(typo(s)), typo(s), s);
});

// 12.09.2026 на /trips/november/hainan/ при 402 px: «...январский дороже ноябрьского на 5 174 ₽»
// переносилось как «на 5» / «174 ₽». Пробела ВНУТРИ числа типограф не знал: число с единицей
// он склеивал, а разряд тысяч оставлял местом переноса — 3078 таких чисел на 1308 страницах.
test('разряд тысяч не рвётся', () => {
  assert.equal(typo('дороже ноябрьского на 5 174 ₽'), `дороже ноябрьского на${N}5${N}174${N}₽`);
  assert.equal(typo('перелёт 10 000 ₽'), `перелёт 10${N}000${N}₽`);
  assert.equal(typo('бюджет 1 234 567 ₽'), `бюджет 1${N}234${N}567${N}₽`);
  assert.equal(typo('население 2 000 000 человек'), `население 2${N}000${N}000${N}человек`);
  // разряд внутри диапазона: обе половины целые, тире и так не рвётся
  assert.equal(typo('от 10 000 до 20 000 ₽'), `от${N}10${N}000${N}до${N}20${N}000${N}₽`);
});
test('телефон и обычные цифры разрядом тысяч не считаются', () => {
  assert.equal(typo('+7 499 653 99 26'), '+7 499 653 99 26');
  assert.equal(typo('8 800 555 26 08'), '8 800 555 26 08');
  assert.equal(typo('+64 21 550 767'), '+64 21 550 767');
  assert.equal(typo('+61 413 004 816'), '+61 413 004 816');
  assert.equal(typo('+354 696 5524'), '+354 696 5524');
  // четыре цифры до пробела — это не разряд, а две отдельные величины
  assert.equal(typo('рейсы 1234 567'), 'рейсы 1234 567');
  // дата и год живут по своим правилам: год склеивается со словом, а не с числом
  assert.equal(typo('2026-09-12'), '2026-09-12');
  assert.equal(typo('в 2026 году'), `в${N}2026${N}году`);
});
test('разряд тысяч: повторный прогон ничего не меняет', () => {
  for (const s of ['на 5 174 ₽', 'от 10 000 до 20 000 ₽', '+7 499 653 99 26', '8 800 555 26 08', 'бюджет 1 234 567 ₽']) {
    assert.equal(typo(typo(s)), typo(s), s);
  }
});

// 12.09.2026: первая версия правила считала телефоном любой хвост через дефис и пропускала
// диапазон «70 000–110 000» — на Антарктиде такие цены и рвались чаще всего.
test('разряд тысяч внутри диапазона тоже склеивается', () => {
  assert.equal(typo('перелёт 70 000–110 000 ₽'), `перелёт 70${N}000–${WJ}110${N}000${N}₽`);
  assert.equal(typo('тур 3 500 000-5 000 000 ₽'), `тур 3${N}500${N}000–${WJ}5${N}000${N}000${N}₽`);
  // у телефона пробел остаётся обычным (дефис в короткое тире превращает давнее правило
  // диапазона — это не наша правка и в задаче не значилось)
  assert.equal(typo('+507 382-2582'), `+507 382–${WJ}2582`);
  assert.equal(typo('+230 696-1545'), `+230 696–${WJ}1545`);
});
