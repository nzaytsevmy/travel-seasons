// Неразрывные пробелы: предлог не висит, число не отрывается, тире не начинает строку.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { typo } from '../src/utils/typo.js';
const N = ' ';

test('короткий предлог и союз склеиваются со следующим словом', () => {
  assert.equal(typo('с ноября по апрель и в мае'), `с${N}ноября по${N}апрель и${N}в${N}мае`);
});
test('число не отрывается от единицы и от слова', () => {
  assert.equal(typo('вода 24–28 °C, в пути 6 часов 20 минут'), `вода 24–${WJ}28${N}°C, в${N}пути 6${N}часов 20${N}минут`);
});
test('тире не начинает строку', () => {
  assert.equal(typo('Маскат — север'), `Маскат${N}— север`);
});
test('заглавная буква в начале предложения тоже считается', () => {
  assert.equal(typo('В Салале в хариф'), `В${N}Салале в${N}хариф`);
});
test('пустое и не строка — как есть', () => {
  assert.equal(typo(''), ''); assert.equal(typo(undefined), undefined);
});

// Замечания Никиты 10.09.2026 на странице Турции: «(макс 90/180)» уезжало «90/180)» одно
// на новую строку, «(~май-июнь)» отрывалось от «плавающая дата». Короткая скобка держится
// за предыдущее слово и не рвётся внутри; диапазон и дробь не рвутся по знаку.
const WJ = '\u2060';
test('короткая скобка держится за слово и не рвётся внутри', () => {
  assert.equal(typo('бесплатно, 60 дней (макс 90/180)'), `бесплатно, 60${N}дней${N}(макс${N}90/${WJ}180)`);
  assert.equal(typo('плавающая дата (~май-июнь)'), `плавающая дата${N}(~май-${WJ}июнь)`);
});
test('диапазон чисел — короткое тире без разрыва, телефон и дата не трогаются', () => {
  assert.equal(typo('около 27-30 мая'), `около 27–${WJ}30${N}мая`);
  assert.equal(typo('+90-312-419-21-22'), '+90-312-419-21-22');
  assert.equal(typo('2026-09-10'), '2026-09-10');
});
test('длинная скобка не приклеивается к слову и не склеивается целиком', () => {
  // внутри работают только обычные правила — предлог держится за следующее слово
  assert.equal(typo('сезон (в горах Каппадокии бывает снег до апреля)'), `сезон (в${N}горах Каппадокии бывает снег до${N}апреля)`);
});

test('повторный прогон ничего не меняет', () => {
  for (const s of ['бесплатно, 60 дней (макс 90/180)', 'плавающая дата (~май-июнь)', 'около 27-30 мая', 'с ноября по апрель и в мае', 'Маскат — север']) {
    assert.equal(typo(typo(s)), typo(s), s);
  }
});

import { typoHtml } from '../tools/typo-dist.mjs';
test('типограф сайта трогает только текст между тегами', () => {
  const html = '<title>Виза в Турцию</title><p data-x="в дом">Виза в <a href="/visa/">Турцию</a> (макс 90/180)</p><script>var a = "в дом";</script><pre>x - y (a b)</pre>';
  const out = typoHtml(html);
  assert.ok(out.includes('<title>Виза в Турцию</title>'), 'title не трогаем');
  assert.ok(out.includes('data-x="в дом"'), 'атрибуты не трогаем');
  assert.ok(out.includes('var a = "в дом";') && out.includes('<pre>x - y (a b)</pre>'), 'скрипт и код не трогаем');
  assert.ok(out.includes(`Виза в${N}<a href="/visa/">`), 'предлог перед ссылкой держится за неё');
  assert.ok(out.includes(`${N}(макс${N}90/${WJ}180)`), 'скобка склеена');
  assert.equal(typoHtml(out), out, 'повторный прогон ничего не меняет');
});
