import test from 'node:test';
import assert from 'node:assert/strict';
import { clipTitle, clipDescription } from '../src/data/news.js';

// Заголовок и описание страницы заметки режутся только по целым словам.
// Замер 11.09.2026: в выдаче стояло «…из Непала в Тибет: 19 мосто…» — так был
// обрезан заголовок у 90 заметок из 119, а описание обрывалось на 200-м знаке.

const nepal = 'Обвал ледника разрушил дорогу из Непала в Тибет: 19 мостов и 40 километров пути';

const wholeWordCut = (src, out) => {
  const body = out.endsWith('…') ? out.slice(0, -1) : out;
  return src.startsWith(body) && (src[body.length] === undefined || src[body.length] === ' ' || /[.:,—]$/.test(body));
};

test('короткий заголовок не трогаем', () => {
  const s = 'Популяция какапо выросла до 325 птиц';
  assert.equal(clipTitle(s), s);
});

test('длинный заголовок режется по границе фразы, а не посреди слова', () => {
  assert.equal(clipTitle(nepal), 'Обвал ледника разрушил дорогу из Непала в Тибет');
});

test('без границы фразы — по целому слову, без висящего числа и предлога', () => {
  const s = 'Карликовые еноты острова Косумель лепят себе мячики из туристического мусора и песка на пляже';
  const t = clipTitle(s);
  assert.ok(t.length <= 60, `${t.length}: ${t}`);
  assert.ok(t.endsWith('…'), t);
  assert.ok(wholeWordCut(s, t), `обрыв посреди слова: ${t}`);
  assert.doesNotMatch(t.slice(0, -1), /\s(\d+|[а-яё]{1,2})$/i, `висит в конце: ${t}`);
});

// Прочитано глазами на всех 90 обрезанных заголовках 11.09.2026: двоеточие и тире
// режут чисто, а запятая — посреди фразы («Кость, брошенную в Арктике в 1948 году»).
// Запятая годится, только если за ней начинается новая часть фразы.
test('запятая режет заголовок, только если за ней «а», «но», «если», «когда»', () => {
  assert.equal(
    clipTitle('Тропы Эль-Чальтена стали платными, а Flexipass покрывает и Перито-Морено'),
    'Тропы Эль-Чальтена стали платными',
  );
  for (const s of [
    'Кость, брошенную в Арктике в 1948 году, опознали через 78 лет: череп шириной 70 сантиметров',
    'Рыбу, потерянную наукой с 1985 года, вытащила сачком для креветок жительница деревни на Сепике',
    'Городскую жёлтую лихорадку в Бразилию, по расчётам, привела засуха, а не дожди',
  ]) {
    const t = clipTitle(s);
    assert.ok(t.endsWith('…'), `обрезано по запятой посреди фразы: ${t}`);
    assert.ok(t.length <= 60 && wholeWordCut(s, t), t);
  }
});

test('в конце обрезки не висят число, предлог или союз', () => {
  for (const s of [
    'Тигров в Непале стало 429, а в парке Банке их 51 при расчётных 28',
    'Кость, брошенную в Арктике в 1948 году, опознали через 78 лет: череп шириной 70 сантиметров',
  ]) {
    const t = clipTitle(s);
    assert.doesNotMatch(t.slice(0, -1), /\s(\d+|[а-яё]{1,2}|для|при|про|без|над|под|через|после|перед|что|как|или)$/i, `висит в конце: ${t}`);
  }
});

// Анализ кода (CodeQL, js/redos) на заявке №600 11.09.2026: выражение для
// висящих хвостов могло перебирать варианты экспоненциально — на 22 повторах
// «таб-цифра» старое думало 1,3 секунды, на 24 — 5,2, дальше вдвое на повтор.
// Внутри обрезки до 60 знаков в этом тесте старый код думал 2,9 секунды.
test('обрезка не зависает на строке из пробелов и цифр', () => {
  const s = ' 0' + '\t0'.repeat(26) + ' zz хвост хвост хвост';
  const t0 = performance.now();
  clipTitle(s);
  const ms = performance.now() - t0;
  assert.ok(ms < 200, `обрезка думала ${Math.round(ms)} мс`);
});

test('описание до 155 знаков кончается на целом предложении, если оно влезает', () => {
  const s = 'Девятого сентября жители Намрунга расчистили старую тропу и положили через реку Теранг временный мост из брёвен и досок. Совет районной администрации при этом действует.';
  assert.equal(
    clipDescription(s),
    'Девятого сентября жители Намрунга расчистили старую тропу и положили через реку Теранг временный мост из брёвен и досок.',
  );
});

// Проверка поисковой части считает описание короче 100 знаков потерянным местом
// в выдаче Яндекса. 11.09.2026 обрезка по первому короткому предложению дала
// 18 таких описаний (75–99 знаков) — короткое предложение одно не годится.
test('короткое первое предложение не остаётся описанием одно: 100–155 знаков', () => {
  const s = 'Жители Намрунга положили через реку Теранг временный мост из брёвен и досок. Совет районной администрации отложить поход по кругу Манаслу при этом действует до нового уведомления.';
  const d = clipDescription(s);
  assert.ok(d.length >= 100 && d.length <= 155, `${d.length}: ${d}`);
  assert.ok(wholeWordCut(s, d), `обрыв посреди слова: ${d}`);
});

test('длинное первое предложение описания режется по целому слову', () => {
  const s = 'Районная администрация Горкхи 6 сентября приостановила походы по треку вокруг Манаслу и через перевал Ларке до нового уведомления: ночной паводок на реке Теранг у деревни Намрунг смыл железный и подвесной мосты.';
  const d = clipDescription(s);
  assert.ok(d.length <= 155, `${d.length}: ${d}`);
  assert.ok(wholeWordCut(s, d), `обрыв посреди слова: ${d}`);
});
