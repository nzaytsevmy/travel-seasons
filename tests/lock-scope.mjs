// 51 секунда. То есть очередь стоила часа на проверке, которая сама считается
// минуты и вдобавок повторяется в облаке.
//
// Отсюда разделение: тяжёлый прогон ждёт очереди, лёгкий идёт мимо.
// Лёгкий — это одновременно:
//   1) явно перечисленные файлы тестов, и все они из белого списка ниже;
//   2) ровно один проект (один браузер);
//   3) без обновления эталонов.
// Любое отклонение — прогон считается тяжёлым. Умолчание в пользу очереди:
// ошибиться в сторону ожидания дёшево, ошибиться в сторону перегруза — это
// перезагрузка ноутбука посреди работы.
//
// ⛔ В белый список попадают только те файлы, которые НЕ снимают эталонных
// скриншотов: память ест не сам браузер, а сравнение картинок по четырём
// проектам. Сторож в tests/lock-scope.test.mjs держит это правило и падает,
// если в список попробуют внести файл со скриншотами.

export const LIGHT_SPECS = new Set([
  'content-invariants.spec.ts',
  'ai-markup-litter.spec.ts',
  'changed-pages-structural.spec.ts',
  'rhythm-gate.spec.ts',
  'news-gate.spec.ts',
  'sitemap-dates.spec.ts',
  'page-mtimes.spec.ts',
  'monetization-browser.spec.ts',
]);

const SPEC_RE = /([^/\\]+\.spec\.ts)$/;

/**
 * Лёгкий ли это прогон Playwright. На вход — argv целиком.
 */
export function isLightRun(argv = []) {
  const args = argv.slice(2);

  // Обновление эталонов всегда тяжёлое: оно пишет картинки по всем проектам.
  if (args.some((a) => a.startsWith('--update-snapshots'))) return false;

  const projects = args.filter((a) => a === '--project' || a.startsWith('--project='));
  if (projects.length !== 1) return false;
  // `--project foo` разбивается на два аргумента; значение обязано быть одно.
  if (projects[0] === '--project') {
    const i = args.indexOf('--project');
    if (!args[i + 1] || args[i + 1].startsWith('-')) return false;
  } else if (projects[0].split('=')[1]?.includes(',')) {
    return false;
  }

  const specs = args.filter((a) => !a.startsWith('-') && SPEC_RE.test(a));
  if (specs.length === 0) return false;               // весь набор — тяжёлый
  return specs.every((s) => LIGHT_SPECS.has(s.match(SPEC_RE)[1]));
}
