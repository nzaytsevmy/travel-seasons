import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

// Даты в карте сайта.
//
// ⛔ Зачем эта проверка. Дата обновления в карте — единственное, чем сайт
//    говорит поиску «вот тут новое, зайди». Она ломалась дважды подряд, и оба
//    раза молча:
//      25.08.2026 — указатель карты отдавал дату старее своего содержимого,
//                   и Google не заходил внутрь вовсе;
//      27.08.2026 — все 1665 служебных страниц получали ОДНУ дату справочных
//                   данных. Правка визовых правил одной страны заявляла поиску
//                   обновление всего сайта, Googlebot уходил перепроверять его
//                   и до новых статей не добирался: вышедшие после 19 августа
//                   он не открыл ни разу.
//    Ни сборка, ни пиксельный прогон, ни проверка выдачи этого не видели.

const КАРТА = 'dist/sitemap-0.xml';
const УКАЗАТЕЛЬ = 'dist/sitemap-index.xml';

type Запись = { путь: string; дата: string };

function записи(): Запись[] {
  const xml = readFileSync(КАРТА, 'utf8');
  const out: Запись[] = [];
  for (const m of xml.matchAll(/<loc>https:\/\/traveltribe\.ru([^<]*)<\/loc><lastmod>([^<]*)<\/lastmod>/g)) {
    out.push({ путь: m[1], дата: m[2].slice(0, 10) });
  }
  return out;
}

test('1. у каждого адреса в карте есть дата обновления', () => {
  const xml = readFileSync(КАРТА, 'utf8');
  const адресов = (xml.match(/<loc>/g) || []).length;
  expect(адресов, 'карта пуста — сборка не прошла?').toBeGreaterThan(1500);
  expect(записи().length, 'у части адресов нет даты').toBe(адресов);
});

test('2. одна дата не покрывает больше трети сайта', () => {
  const все = записи();
  const счёт = new Map<string, number>();
  for (const з of все) счёт.set(з.дата, (счёт.get(з.дата) || 0) + 1);
  const [дата, сколько] = [...счёт.entries()].sort((a, b) => b[1] - a[1])[0];
  const доля = сколько / все.length;
  expect(доля,
    `дата ${дата} стоит у ${сколько} адресов из ${все.length} (${Math.round(доля * 100)}%). ` +
    `Так выглядит общая дата, розданная всем скопом: поиск читает это как «сайт переписан целиком» ` +
    `и уходит перепроверять старое вместо новых страниц.`).toBeLessThan(0.34);
});

test('3. страницы про одну страну не ходят датой за другими', () => {
  const все = записи();
  const дата = (п: string) => все.find((з) => з.путь === п)?.дата;
  // ⛔ До 12.09.2026 здесь сверялись сборы и «по месяцам» про одну страну: считалось, что они
  //    питаются одними данными. Посылка неверна — шаблон «по месяцам» не читает ни гидов, ни
  //    фактов «на месте», ни розеток, ни визовых строк (сверено сравнением готовых страниц: у
  //    Кипра, Узбекистана и Турции 0 изменённых строк при правке этих данных). Из-за общей даты
  //    правка объявляла свежими 1564 адреса из 2182 — 72% карты. Теперь дата считается по типу
  //    страниц, и равенство обязано держаться ВНУТРИ типа: разные месяцы одной страны и одного
  //    типа питаются одним и тем же.
  for (const страна of ['turkey', 'south-korea', 'georgia', 'japan']) {
    for (const [тип, сент, окт] of [
      ['сборы', `/packing/${страна}/september/`, `/packing/${страна}/october/`],
      ['по месяцам', `/trips/september/${страна}/`, `/trips/october/${страна}/`],
    ] as const) {
      const a = дата(сент), b = дата(окт);
      if (!a || !b) continue;
      expect(b, `у страниц «${тип}» про ${страна} даты разошлись между месяцами`).toBe(a);
    }
  }
  // Раздача по типам обязана быть живой, а не одной датой под другим именем: хотя бы у одной
  // страны дата сборов и дата «по месяцам» различаются.
  const различаются = ['turkey', 'south-korea', 'georgia', 'japan', 'vietnam', 'egypt', 'cyprus'].some((с) => {
    const a = дата(`/packing/${с}/september/`), b = дата(`/trips/september/${с}/`);
    return a && b && a !== b;
  });
  expect(различаются,
    'дата сборов и дата «по месяцам» совпали у всех стран — значит раздача по типам страниц не работает').toBe(true);
  // А у разных стран даты обязаны различаться: иначе это снова общая дата.
  const по_странам = ['turkey', 'south-korea', 'georgia', 'japan', 'vietnam', 'egypt']
    .map((с) => дата(`/packing/${с}/september/`)).filter(Boolean);
  expect(new Set(по_странам).size,
    'у всех стран одна и та же дата — значит она снова общая, а не своя').toBeGreaterThan(1);
});

test('4. указатель карты не старше самой свежей страницы внутри', () => {
  const у = readFileSync(УКАЗАТЕЛЬ, 'utf8').match(/<lastmod>([^<]*)<\/lastmod>/)?.[1]?.slice(0, 10);
  expect(у, 'у указателя карты нет даты').toBeTruthy();
  const свежая = записи().map((з) => з.дата).sort().at(-1)!;
  expect(у! >= свежая,
    `указатель заявляет ${у}, а внутри есть страница от ${свежая}. ` +
    `Google читает указатель первым и внутрь не заходит.`).toBe(true);
});

test('5. заметки новостей не сидят на общей справочной дате', () => {
  const заметки = записи().filter((з) => /^\/novosti\/\d{4}-\d{2}-\d{2}-/.test(з.путь));
  expect(заметки.length, 'заметок в карте нет — раздел пропал?').toBeGreaterThan(20);
  const счёт = new Map<string, number>();
  for (const з of заметки) счёт.set(з.дата, (счёт.get(з.дата) || 0) + 1);
  const крупнейшая = Math.max(...счёт.values());
  expect(крупнейшая / заметки.length,
    'все заметки с одной датой — значит взята общая, а не дата сверки каждой').toBeLessThan(0.9);
});
