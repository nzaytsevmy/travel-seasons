import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

// ⛔ ЗАЧЕМ. 04.09.2026 замер Google: 64 запроса, 697 показов и НОЛЬ переходов там,
// где страновая витрина /<страна>/ и визовая страница /visa/<страна>/ стоят на одном
// и том же вопросе. Затронуто 30 направлений, крупнейшее — Дагестан (322 показа).
// Причина: обе страницы клали в разметку вопросов-ответов ОДИН И ТОТ ЖЕ вопрос
// «Нужна ли виза X для россиян» с одним и тем же текстом ответа (vd.summary).
// Google не мог выбрать владельца и на «карелия нужен ли загранпаспорт» ставил
// витрину на 1-е место, а на «нужен ли загранпаспорт в карелию» — визовую на 1,8.
// Владелец визового интента — /visa/<страна>/. Витрина отвечает коротко и уводит.

const root = new URL('../', import.meta.url);
const read = (p) => readFile(new URL(p, root), 'utf8');

test('визовый вопрос в разметке принадлежит только визовой странице', async () => {
  const [hub, visa] = await Promise.all([
    read('src/pages/[slug].astro'),
    read('src/pages/visa/[slug].astro'),
  ]);

  assert.match(
    visa,
    /q: `Нужна ли виза \$\{d\.cases\.vP\} для россиян/,
    'визовая страница потеряла свой собственный вопрос — тогда интент осиротеет',
  );

  assert.doesNotMatch(
    hub,
    /q: `Нужна ли виза /,
    'страновая витрина снова кладёт визовый вопрос в разметку и спорит с /visa/<страна>/',
  );
});

test('витрина всё равно отвечает читателю и уводит на визовую страницу', async () => {
  const hub = await read('src/pages/[slug].astro');
  assert.match(hub, /vd\.summary/, 'витрина перестала называть визовый статус видимым текстом');
  assert.match(hub, /href=\{`\/visa\/\$\{d\.slug\}\/`\}/, 'с витрины пропала ссылка на визовую страницу');
});
