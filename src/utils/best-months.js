// Лучшие и худшие месяцы направления — одна логика для страниц страны, визы, поездок по месяцам и сборов.
// Лучшие — месяцы «пика», а где пика нет, «хорошие»; худшие — «закрыто», а где его нет, «не сезон». Называем
// их сезонами подряд: «июнь–август», «декабрь–март, июнь–июль и октябрь».
// ⛔ До 11.09.2026 брались первые три хороших месяца по календарю, и фраза называла только первый сезон:
//    у Исландии и Норвегии — «январь, февраль, март» при пике в июне–августе. 12.09.2026 та же ошибка нашлась
//    на страницах виз, поездок по месяцам и сборов — поэтому логика вынесена сюда и общая для всех четырёх.
import { MONTHS } from '../data/directions.js';

const RANK = { P: 4, G: 3, O: 2, B: 1, X: 0 };
const МЕС_КОР = ['янв', 'фев', 'мар', 'апр', 'май', 'июн', 'июл', 'авг', 'сен', 'окт', 'ноя', 'дек'];

const сезоныИз = (ms) => {
  const g = [];
  for (const m of ms) { const last = g.at(-1); if (last && m.i === last.at(-1).i + 1) last.push(m); else g.push([m]); }
  // Сезон через Новый год — один, а не два: декабрь приклеивается к январю.
  if (g.length > 1 && g[0][0].i === 0 && g.at(-1).at(-1).i === 11) g.unshift([...g.pop(), ...g.shift()]);
  return g;
};
const сезонСловами = (s) => (s.length > 1 ? `${s[0].nom}–\u2060${s.at(-1).nom}` : s[0].nom);
const сезоныСловами = (g) => (g.length > 1 ? `${g.slice(0, -1).map(сезонСловами).join(', ')} и ${сезонСловами(g.at(-1))}` : g.map(сезонСловами).join(''));

export function месяцыНаправления(d) {
  const r = d.r || [];
  const monthsRanked = MONTHS.map((m, i) => ({ ...m, i, status: r[i], text: d.t?.[i], rank: RANK[r[i]] || 0 }));
  const пик = monthsRanked.filter((m) => m.status === 'P');
  const bestMonths = пик.length ? пик : monthsRanked.filter((m) => m.status === 'G');
  const лучшиеСезоны = сезоныИз(bestMonths);
  const круглыйГод = bestMonths.length === 12;
  const лучшиеСловами = круглыйГод ? 'круглый год' : сезоныСловами(лучшиеСезоны);
  // В описании для поиска и в карточке для соцсетей места мало: два самых длинных сезона в порядке календаря.
  const двеДлинных = лучшиеСезоны.filter((s) => [...лучшиеСезоны].sort((a, b) => b.length - a.length).slice(0, 2).includes(s));
  const лучшиеКоротко = круглыйГод ? 'круглый год' : сезоныСловами(двеДлинных);
  // Карточка фактов наверху страницы страны на компьютере значения не переносит, и полное «декабрь–февраль
  // и август–сентябрь» вылезало за её край (11.09.2026). Там сезоны сокращениями, как в каталоге стран.
  const лучшиеВКарточке = круглыйГод ? 'круглый год'
    : двеДлинных.map((s) => (s.length > 1 ? `${МЕС_КОР[s[0].i]}–\u2060${МЕС_КОР[s.at(-1).i]}` : МЕС_КОР[s[0].i])).join(', ');
  const закрыто = monthsRanked.filter((m) => m.status === 'X');
  const worstMonths = закрыто.length ? закрыто : monthsRanked.filter((m) => m.status === 'B');
  const худшиеСловами = worstMonths.length ? сезоныСловами(сезоныИз(worstMonths)) : '';
  // Для ссылок на месяцы: лучшие месяцы в порядке сезонов, сезон через Новый год — с его начала.
  const лучшиеПоСезонам = лучшиеСезоны.flat();
  return { monthsRanked, bestMonths, лучшиеСезоны, лучшиеСловами, лучшиеКоротко, лучшиеВКарточке, worstMonths, худшиеСловами, лучшиеПоСезонам };
}
