// Неразрывные пробелы по правилам русской типографики: предлог или союз не остаётся
// в конце строки, число не отрывается от единицы и от следующего слова, тире не
// начинает строку. Замечание Никиты 09.09.2026 на странице Омана: «с» повисало в
// конце строки, «°C» уезжало на следующую.
//
// 10.09.2026 на странице Турции: «(макс 90/180)» уезжало «90/180)» одно на новую
// строку, «(~май-июнь)» отрывалось от «плавающая дата». Отсюда три правила ниже:
// короткая скобка не рвётся внутри (перенос перед «(» допустим), диапазон чисел идёт через
// короткое тире без разрыва, дробь не рвётся по косой черте. Разрыв запрещает
// невидимый знак WORD JOINER (U+2060): браузер не переносит строку ни до, ни после него.
//
// Применять к готовым строкам текста (подписи, ответы FAQ, значения таблиц, абзацы).
// HTML внутрь не подавать: разметка меняться не должна.
const NBSP = '\u00A0';
const WJ = '\u2060';
const SHORT = 'в|во|с|со|к|ко|у|о|об|от|до|за|на|по|из|при|и|а|но|не|ни|же|ли|бы|для|над|под|без|про|или|что|как';
const RE_PREP = new RegExp(`(^|[\\s(«„])(${SHORT}) (?=\\S)`, 'gi');
const RE_NUM_UNIT = /(\d)\s(?=°C|°|%|₽|\$|€|мм|км\b|м\b|ч\b|мин\b|дн|дней|день|дня|час|лет|год|тыс|млн)/g;
const RE_NUM_WORD = /(\d)\s(?=[а-яё])/gi;
const RE_DASH = /\s—\s/g;
// «27-30», «24–28»: до четырёх цифр с каждой стороны; телефон «+90-312-419» и дата
// «2026-09-10» — цепочки через дефис — не трогаются.
const RE_RANGE = /(?<![\d+\-–])(\d{1,4})\s?[-–]\s?(\d{1,4})(?![\d\-–])/g;
const RE_SLASH = /(\d)\/(\d)/g;
// Скобка до 24 знаков без вложенных скобок; длинная переносится как обычный текст.
const RE_PAREN = /\s\(([^()\n]{1,24})\)/g;

export function typo(text) {
  if (typeof text !== 'string' || !text) return text;
  let t = text;
  // дважды: после первой замены следующий короткий предлог мог стоять сразу за неразрывным
  for (let i = 0; i < 2; i++) t = t.replace(RE_PREP, (m, pre, w) => `${pre}${w}${NBSP}`);
  t = t.replace(RE_NUM_UNIT, `$1${NBSP}`);
  t = t.replace(RE_NUM_WORD, `$1${NBSP}`);
  t = t.replace(RE_DASH, `${NBSP}— `);
  t = t.replace(RE_RANGE, `$1–${WJ}$2`);
  t = t.replace(RE_SLASH, `$1/${WJ}$2`);
  t = t.replace(RE_PAREN, (m, inner) => `${m[0]}(${inner.replace(/ /g, NBSP).replace(/-(?![\s\u2060])/g, `-${WJ}`).replace(/\/(?![\s\u2060])/g, `/${WJ}`)})`);
  return t;
}
