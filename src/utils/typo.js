// Неразрывные пробелы по правилам русской типографики: предлог или союз не остаётся
// в конце строки, число не отрывается от единицы и от следующего слова, тире не
// начинает строку. Замечание Никиты 09.09.2026 на странице Омана: «с» повисало в
// конце строки, «°C» уезжало на следующую.
//
// 10.09.2026 на странице Турции: «(макс 90/180)» уезжало «90/180)» одно на новую
// строку, «(~май-июнь)» отрывалось от «плавающая дата». Отсюда три правила ниже:
// короткая скобка не рвётся внутри и держится за короткий кусок перед ней, диапазон чисел идёт через
// короткое тире без разрыва, дробь не рвётся по косой черте. Разрыв запрещает
// невидимый знак WORD JOINER (U+2060): браузер не переносит строку ни до, ни после него.
//
// Применять к готовым строкам текста (подписи, ответы FAQ, значения таблиц, абзацы).
// HTML внутрь не подавать: разметка меняться не должна.
const NBSP = '\u00A0';
const WJ = '\u2060';
const SHORT = 'в|во|с|со|к|ко|у|о|об|от|до|за|на|по|из|при|и|а|но|не|ни|же|ли|бы|для|над|под|без|про|или|что|как';
const RE_PREP = new RegExp(`(^|[\\s(«„])(${SHORT}) (?=\\S)`, 'gi');
const RE_NUM_UNIT = /(\d)\s(?=°C|°|%|₽|\$|€|мм|км\b|м\b|ч\b|мин\b|дн|дней|день|дня|час|лет|год|тыс|млн)/g;
const RE_NUM_WORD = /(\d)\s(?=[а-яё])/gi;
// Разряд тысяч: «5 174», «10 000», «1 234 567». Пробел внутри числа — не место для переноса:
// 12.09.2026 на странице Хайнаня «дороже на 5 174 ₽» переносилось как «на 5» / «174 ₽».
// Телефоном (и потому не числом) считается цепочка, за последней тройкой которой идёт ещё
// группа цифр — «8 800 555 26 08», «+7 499 653 99 26», «+593 2 252-6361», — и цепочка за кодом
// страны: «+64 21 550 767», «+61 413 004 816». Их не трогаем: это не число, а набор групп.
const RE_THOUSANDS = /(?<![\d.,])\d{1,3}(?: \d{3})+(?!\d)/g;
// Хвост телефона: ещё одна группа через пробел («653 99 26») или через дефис группа из
// четырёх цифр («696-1545»). Диапазон «70 000–110 000» под это не подходит — справа тройка.
const PHONE_TAIL = /^ \d|^[-\u2013]\d{4}/;
const PHONE_CODE = /\+\d{1,4} $/;
const RE_DASH = /\s—\s/g;
// «27-30», «24–28»: до четырёх цифр с каждой стороны; телефон «+90-312-419» и дата
// «2026-09-10» — цепочки через дефис — не трогаются.
const RE_RANGE = /(?<![\d+\-–])(\d{1,4})\s?[-–]\s?(\d{1,4})(?![\d\-–])/g;
const RE_SLASH = /(\d)\/(?=\d)/g;
// Скобка до 24 знаков без вложенных скобок; длинная переносится как обычный текст.
const RE_PAREN = /\s\(([^()\n]{1,24})\)/g;
// Короткая скобка держится за кусок перед ней, только если вместе они не длиннее 24 знаков:
// «дата (~май-июнь)» не отрывается (жалоба Никиты 10.09.2026), а «для Каппадокии (тропы
// каменистые)» — 33 знака — не клеится: на телефоне такой кусок шире строки рвался посреди
// слова. Правило сведено с сессией Сортовника в тот же день.
const GLUE_MAX = 24;
const visible = (x) => x.replace(/\u2060/g, '').length;

export function typo(text) {
  if (typeof text !== 'string' || !text) return text;
  let t = text;
  // дважды: после первой замены следующий короткий предлог мог стоять сразу за неразрывным
  for (let i = 0, prev = ''; i < 6 && prev !== t; i++) { prev = t; t = t.replace(RE_PREP, (m, pre, w) => `${pre}${w}${NBSP}`); }
  t = t.replace(RE_THOUSANDS, (m, offset, str) => {
    const before = str.slice(Math.max(0, offset - 6), offset);
    const after = str.slice(offset + m.length, offset + m.length + 5);
    const phone = PHONE_TAIL.test(after) || PHONE_CODE.test(before) || (before.endsWith('+') && m.split(' ').length > 2);
    return phone ? m : m.split(' ').join(NBSP);
  });
  t = t.replace(RE_NUM_UNIT, `$1${NBSP}`);
  t = t.replace(RE_NUM_WORD, `$1${NBSP}`);
  t = t.replace(RE_DASH, `${NBSP}— `);
  t = t.replace(RE_RANGE, `$1–${WJ}$2`);
  t = t.replace(RE_SLASH, `$1/${WJ}`);
  t = t.replace(RE_PAREN, (m, inner, offset, str) => {
    const body = `(${inner.replace(/ /g, NBSP).replace(/[-–](?![\s\u2060])/g, (d) => d + WJ).replace(/\/(?![\s\u2060])/g, `/${WJ}`)})`;
    // неразрывный кусок перед скобкой — от последнего обычного пробела
    const before = str.slice(0, offset);
    const run = before.slice(Math.max(before.lastIndexOf(' '), before.lastIndexOf('\n'), before.lastIndexOf('\t')) + 1);
    return (visible(run) + 1 + visible(body) <= GLUE_MAX ? NBSP : m[0]) + body;
  });
  return t;
}
