/**
 * Дата свежести статьи — поздняя из двух: первой публикации и updatedDate.
 * По ней сортируются ленты, она уходит в карту сайта, в dateModified разметки
 * и в строку «обновлено» на странице статьи.
 *
 * ⛔ Журнал проверок (checks) дату НЕ двигает — ни одна запись, ни с признаком
 * minor, ни без него. История: с 14.08.2026 дата считалась из последней записи
 * журнала, а гейт требует запись при любой правке прозы — даже добавленной
 * ссылке. 07.09.2026 64 статьи получили одну дату без единого изменённого
 * слова; заплатка minor: true требовала помнить о ней руками, и 08.09 следующие
 * заходы снова подняли даты. Замер 09.09.2026: в ленте 29 статей из 102 датированы
 * сентябрём, по-настоящему переработанных среди них 13. Никита 09.09.2026: «даты
 * старых статей обновляются постоянно — этого делать нельзя».
 *
 * Теперь дату двигает только updatedDate, а её ставит только переработка
 * (scripts/edit-kind.mjs: больше 40 изменённых слов прозы, заголовок или
 * описание). Гейт в tests/content-invariants.spec.ts следит за обеими сторонами:
 * переработка без новой updatedDate и мелкая правка со сдвинутой updatedDate —
 * красные. Записи журнала остаются обязательными и видны читателю на странице
 * статьи как «проверено» — это другая дата, дата сверки фактов.
 */
export function freshDate(data) {
  const dates = [data.pubDate, data.updatedDate].filter(Boolean).map((d) => d.valueOf());
  return new Date(Math.max(...dates));
}

/**
 * Второй ключ лент: при равной дате порядок задаёт адрес (slug).
 *
 * ⛔ Без него равные даты оставались в том порядке, в каком сборка прочитала файлы, а он
 * от сборки к сборке разный. 11.09.2026 две сборки одного коммита разошлись в ленте блога,
 * страницах тегов, RSS, ленте Дзена и карте картинок: пять статей с датой 3 сентября
 * вставали то так, то эдак. Сравнение посимвольное, без правил языка, чтобы порядок не
 * зависел и от настроек машины. Сторож — tests/stable-order.test.mjs.
 */
export const slugOrder = (a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0);

/** Сортировка «свежее сверху» для лент. */
export const byFreshness = (a, b) => freshDate(b.data).valueOf() - freshDate(a.data).valueOf() || slugOrder(a, b);

/** По дате первой публикации, свежее сверху: так идут RSS и лента Дзена. */
export const byPubDate = (a, b) => b.data.pubDate.valueOf() - a.data.pubDate.valueOf() || slugOrder(a, b);
