/**
 * Дата свежести статьи — поздняя из трёх: первой публикации, старого поля
 * updatedDate и последней записи журнала сверок.
 *
 * Зачем отдельный счёт. Страница статьи считала дату обновления по журналу
 * сверок ещё с 14.08.2026, а лента блога и карта сайта знали только pubDate.
 * 26.08.2026 это вылезло: переработанная статья про визу в Черногорию выросла
 * с 846 слов до 2 431, но осталась 23-й в ленте и ушла в карту сайта датой
 * 1 августа — для поисковика страница месячной давности. Замер в тот день:
 * 62 статьи из 82 показывали дату старше своей последней правки.
 *
 * Дату первой публикации это не подменяет: pubDate остаётся как есть и идёт
 * в разметку как datePublished. Здесь считается только «когда трогали
 * последний раз» — то, по чему сортируют ленту и что уходит в lastmod.
 *
 * ⛔ Правка ради косметики сюда попадать не должна: запись в журнале сверок
 * появляется после настоящей сверки, иначе дата станет полем, которое нечем
 * проверить, и её начнут подкручивать без правок.
 */
export function freshDate(data) {
  const dates = [data.pubDate, data.updatedDate, ...(data.checks ?? []).map((c) => c.date)];
  return new Date(Math.max(...dates.filter(Boolean).map((d) => d.valueOf())));
}

/** Сортировка «свежее сверху» для лент. */
export const byFreshness = (a, b) => freshDate(b.data).valueOf() - freshDate(a.data).valueOf();
