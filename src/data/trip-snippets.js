// Заголовок и описание для выдачи — по конкретной паре «месяц × направление»,
// поверх формулы страницы поездки.
//
// Зачем. Формула в pages/trips/[month]/[country].astro собирает один заголовок на
// все 852 страницы: «{Страна} в {месяце} {год}: погода, цены, виза», а описание —
// «Стоит ли ехать … — погода, цены, виза для россиян, бюджет на неделю». Заголовок
// погоду ОБЕЩАЕТ, но не называет; описание повторяет тот же список словами.
//
// Что видно в выдаче Google 08.09.2026 (смотрелось глазами, запросы «погода в
// испании в ноябре» и «хайнань погода в сентябре 2026»): виджета погоды на этих
// запросах НЕТ, это обычные синие ссылки, и КАЖДЫЙ конкурент выше несёт число
// прямо в сниппете — «+25…+30 °C», «днём 30 °C, ночью 24 °C», «+20 °C». Наше
// описание Google игнорирует и подставляет вместо него кусок таблицы со страницы
// («Температура5-14°C · Осадки53 мм / 7 дн · Тип климатаУмеренный климат…»).
// Человек выбирает из десяти ссылок с числами ту, где число уже видно.
//
// Замер Search Console 09.08–05.09.2026 по 12 адресам ниже: 1535 показов,
// 10 кликов (0,65%) при внутреннем эталоне сайта 1,0–2,0% на тех же позициях
// 8,2–12,3.
//
// ⛔ Числа НЕ переписаны сюда строкой намеренно: они берутся из тех же
//    климатических норм, которые страница печатает в таблице
//    (data/country-monthly-weather.js). Вписанное число молча протухло бы при
//    пересъёмке норм, а расхождение сниппета со страницей — это ровно то, за что
//    Яндекс наказывает как за недобросовестные действия.
// ⛔ Слово «погода» из заголовка НЕ убирается. Пилот WEATHER_REFRAME_PILOT
//    (05.07.2026, 10 страниц) убрал его и увёл заголовок в «стоит ли ехать»:
//    замер 08.09.2026 показал, что доля кликов пилота относительно контроля не
//    изменилась (2,36× до правки → 2,23× после). Здесь обещание заменяется
//    фактом, а не интент подменяется другим.
// ⛔ Город замера назван в описании: у Испании нормы сняты по Мадриду (центр),
//    и 15 °C рядом с «+20 °C» конкурентов с побережья без города читались бы как
//    другая страна. Честность здесь дороже красивого числа.
// ⛔ Адрес, canonical и H1 не трогаются: меряется сниппет.
// ⛔ Взяты только БУДУЩИЕ месяцы. У страниц прошедших месяцев показы падают сами,
//    и правило вердикта «показов в день не меньше 80%» выдало бы ложный ОТКАТ.
//    Сентябрь не взят по той же причине: он кончится до 28-го дня замера.
// ⛔ Страницы пилота WEATHER_REFRAME_PILOT сюда не попадают: у них другой
//    заголовок, и смешение испортило бы оба замера.
//
// Ключ — «{слаг месяца}/{слаг направления}». Остальные 527 страниц типа идут по
// формуле и служат контролем замера.
export const TRIP_SNIPPET_PAGES = new Set([
  'january/egypt',        // 265 показов, 3 клика, позиция 10,0
  'november/spain',       // 254 показа, 1 клик,  позиция 9,0
  'october/vietnam',      // 186 показов, 2 клика, позиция 12,2
  'november/japan',       // 159 показов, 1 клик,  позиция 9,1
  'october/cyprus',       // 157 показов, 1 клик,  позиция 10,8
  'november/south-korea', // 115 показов, 2 клика, позиция 8,2
  'january/philippines',  //  91 показ,   0 кликов, позиция 10,2
  'october/mexico',       //  72 показа,  0 кликов, позиция 9,2
  'november/china',       //  64 показа,  0 кликов, позиция 9,3
  'october/hong-kong',    //  60 показов, 0 кликов, позиция 10,8
  'november/italy-north', //  60 показов, 0 кликов, позиция 8,6
  'march/bali',           //  52 показа,  0 кликов, позиция 12,3
]);

export function hasTripSnippet(monthSlug, countrySlug) {
  return TRIP_SNIPPET_PAGES.has(`${monthSlug}/${countrySlug}`);
}

// Описание собирается из тех же чисел, что печатает таблица на странице.
// Хвост про бюджет добавляется, только если описание без него короче 120 знаков:
// у длинных вердиктов и длинных названий городов строка иначе вылезала за 155,
// а поиск обрезает хвост (то же решение, что в seasons/[country]/[month].astro).
// «3 дождливых дней» — не по-русски. Число согласуется с существительным:
// 1 день, 2–4 дня, 5–20 дней, 21 день, 22 дня; 11–14 всегда «дней».
function rainDays(n) {
  const t = n % 100, o = n % 10;
  if (t >= 11 && t <= 14) return `${n} дождливых дней`;
  if (o === 1) return `${n} дождливый день`;
  if (o >= 2 && o <= 4) return `${n} дождливых дня`;
  return `${n} дождливых дней`;
}

export function tripSnippetDescription(weather, verdict) {
  const head = `Ночью ${weather.tmin} °C, ${rainDays(weather.days)} за месяц, замер по городу ${weather.city}. ${verdict}.`;
  const tail = ' Бюджет на неделю, виза и что делать на месте.';
  return (head + tail).length <= 155 ? head + tail : head;
}
