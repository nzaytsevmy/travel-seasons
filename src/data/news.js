// Помощники ленты /novosti/. Держим отдельно от страниц, чтобы одна и та же
// логика деления «свежее / архив» использовалась и лентой, и архивами, и RSS,
// и тестами — иначе разъедется и появятся заметки, не видимые нигде.

import { slugOrder } from './freshness.js';

export const TOPIC_LABEL = {
  visa: 'Визы и въезд',
  nature: 'Природа',
  transport: 'Транспорт и доступ',
};

export const IMPACT_LABEL = {
  high: 'важно',
  medium: '',
};

const MONTHS_GEN = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
                    'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
const MONTHS_NOM = ['Январь', 'Февраль', 'Март', 'Апрель', 'Май', 'Июнь',
                    'Июль', 'Август', 'Сентябрь', 'Октябрь', 'Ноябрь', 'Декабрь'];

export function formatDateRu(d) {
  const dt = d instanceof Date ? d : new Date(d);
  return `${dt.getUTCDate()} ${MONTHS_GEN[dt.getUTCMonth()]} ${dt.getUTCFullYear()}`;
}

export function monthKey(d) {
  const dt = d instanceof Date ? d : new Date(d);
  return `${dt.getUTCFullYear()}-${String(dt.getUTCMonth() + 1).padStart(2, '0')}`;
}

export function monthTitleRu(key) {
  const [y, m] = key.split('-').map(Number);
  return `${MONTHS_NOM[m - 1]} ${y}`;
}

// Месяцы, у которых есть заметки, — свежий первым. Страница архива строится под
// КАЖДЫЙ из них, включая текущий.
//
// ⛔ Раньше архив полагался только месяцам старше 30 дней, а лента показывала
// все остальные. Из-за этого её длина зависела не от замысла, а от дня месяца
// и темпа публикации: замер 08.09.2026 — 87 заметок и 230 КБ на одной странице,
// и к концу месяца было бы больше. Прежнее условие защищало от дня, когда
// заметка не видна нигде; архив у каждого месяца снимает этот риск полностью —
// заметка попадает в свой месяц в день выпуска.
export function monthKeys(entries) {
  return [...new Set(entries.map((e) => monthKey(e.data.date)))].sort().reverse();
}

/** Когда заметка попала в ленту. У старых заметок это `checked`. */
export const addedAt = (e) => (e.data.added ?? e.data.checked).valueOf();

// Сортировка ленты: СНАЧАЛА дата добавления, при равенстве — дата события.
//
// Раньше главным ключом была дата события, и это давало ленту, где свежее
// уезжает вниз: 03.08.2026 две только что добавленные заметки встали пятой и
// шестой, потому что их события случились 26 и 28 июля, а у соседей — 30 и 31.
// Читатель приходит за новым, значит сверху должно быть добавленное последним.
//
// Дата события при этом никуда не делась: она остаётся в тексте и решает, в
// какой месяц архива заметка попадёт.
//
// При равенстве обеих дат порядок задаёт адрес заметки: иначе заметки одного дня стояли
// в порядке чтения файлов, и две сборки одного коммита расходились в архивах месяцев,
// RSS и ссылках на соседние заметки (11.09.2026).
const byDateDesc = (a, b) =>
  addedAt(b) - addedAt(a) ||
  b.data.date.valueOf() - a.data.date.valueOf() ||
  slugOrder(a, b);

export function entriesOfMonth(entries, key) {
  return entries.filter((e) => monthKey(e.data.date) === key).sort(byDateDesc);
}

// Сколько свежих заметок лента показывает карточкой — с кадром и капсулой-
// ответом. Дальше идёт компактный список строкой: при 2–4 заметках в день лента
// иначе растёт до сотен килобайт, и читатель на телефоне листает её минутами.
export const FULL_ON_FEED = 8;

// Сколько заметок вообще попадает на ленту: восемь карточкой плюс шестнадцать
// строкой — примерно неделя выпуска при нынешнем темпе. Число ПОСТОЯННОЕ, и в
// этом весь смысл: до 08.09.2026 хвост ленты тянул весь текущий месяц и рос
// каждый день (87 заметок, 230 КБ, 37 экранов телефона). Остальное живёт в
// архиве своего месяца.
export const FEED_SIZE = 24;

/** Адрес заметки. У каждой он свой и не зависит от того, где заметка показана. */
export const newsUrl = (slugOrEntry) =>
  `/novosti/${typeof slugOrEntry === 'string' ? slugOrEntry : slugOrEntry.slug}/`;

/**
 * Свежие заметки про страну — для блока на странице направления.
 * Связь идёт по полю `countries` заметки: там слаг направления сайта.
 */
export function newsForCountry(entries, slug, limit = 3) {
  return entries
    .filter((e) => (e.data.countries ?? []).includes(slug))
    .sort(byDateDesc)
    .slice(0, limit);
}

/**
 * Когда заметка выпущена. Это и есть pubDate для RSS: читалки, Дзен и Telegram
 * сортируют ленту по нему. Дата события живёт отдельно, в `data.date`, и уходит
 * в текст заметки и в выбор месяца архива.
 *
 * ⛔ 07.09.2026 обе ленты клали сюда дату события, и свежее уезжало вниз: у
 * заметки дня про событие 3 сентября дата была 3 сентября, и в ленте Дзена она
 * стояла девятой, ниже позавчерашних. На самой странице /novosti/ ровно это
 * чинили 03.08.2026 — до лент правка тогда не дошла.
 */
export const publishedAt = (e) => new Date(addedAt(e));

/** Заметки для RSS: тот же порядок, что на странице, и срез уже после сортировки. */
export function feedEntries(entries, limit) {
  const sorted = [...entries].sort(byDateDesc);
  return typeof limit === 'number' ? sorted.slice(0, limit) : sorted;
}
