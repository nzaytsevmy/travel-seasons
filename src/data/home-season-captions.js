function pointCaption(slug, month) {
  const point = climate.places[slug];
  const context = PLACES[slug];
  if (!point || !context || point.months.length !== 12) throw new Error(`Нет климатической основы подписи: ${slug}`);
  const { tmax, tmin, days } = point.months[month - 1];
  const warmth = tmax < 0 ? 'морозно' : tmax < 10 ? 'холодно' : tmax < 18 ? 'прохладно' : tmax < 30 ? 'тепло' : 'жарко';
  const caveat = days >= 15 ? ', часты осадки' : tmin <= 12 && tmax >= 18 ? ', вечера прохладные' : days <= 4 ? ', осадков немного' : '';
  return `${context[0]} днём обычно ${warmth}${caveat}. ${context[1]}`;
}

