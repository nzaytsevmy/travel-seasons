export const HOME_SEASON_CAPTIONS = Object.fromEntries(Object.keys(PLACES).map(slug => {
  const notes = Array.from({ length: 12 }, (_, i) => pointCaption(slug, i + 1));
  const assigned = new Set();
  for (const [months, caption] of SEASONAL[slug] || []) {
    for (const month of months) {
      if (!Number.isInteger(month) || month < 1 || month > 12 || assigned.has(month)) throw new Error(`Пересечение сезонных подписей: ${slug}/${month}`);
      assigned.add(month);
      notes[month - 1] = caption;
    }
  }
  return [slug, notes];
}));

export function withHomeSeasonCaptions(rows) {
  return rows.map(row => {
    const notes = HOME_SEASON_CAPTIONS[row.slug];
    if (!notes) throw new Error(`Нет сезонных подписей главной: ${row.slug}`);
    return { ...row, seasonReasons: [...notes] };
  });
}
