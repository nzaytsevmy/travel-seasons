//
// Помесячный климат для графика года на странице страны: дневной максимум, дни с
// осадками и температура воды по одной-двум точкам направления.
//
// ⛔ ЧИСЛА НЕ ПРАВИТЬ РУКАМИ. Они собраны разбором таблиц climatestotravel.com
//    (scripts/climate/build.py) и лежат в climate-chart.generated.json вместе с
//    адресом источника и датой сверки. Разбор проверен оракулом: на Омане он обязан
//    повторить шесть рядов, сверенных вручную 08–09.09.2026, и повторяет.
//    Пересобрать: python3 scripts/climate/build.py <каталог страниц>.
//
// ⛔ ВЫБОР ГОРОДОВ — РУЧНОЙ, он в scripts/climate/cities.js. Автоматический «два
//    самых разных города страны» ставил Гагре — Батуми, Алтаю — Мурманск, Гоа —
//    Мумбаи. Десяти направлениям графика нет вовсе, и там же записано почему.
import generated from './climate-chart.generated.json' with { type: 'json' };

const МЕС_П = ['январе', 'феврале', 'марте', 'апреле', 'мае', 'июне',
  'июле', 'августе', 'сентябре', 'октябре', 'ноябре', 'декабре'];
const МЕС_И = ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь',
  'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'];

// «1 день, 2 дня, 5 дней» — иначе подпись читается машинным.
function дней(n) {
  const d10 = n % 10, d100 = n % 100;
  if (d10 === 1 && d100 !== 11) return `${n} день`;
  if (d10 >= 2 && d10 <= 4 && (d100 < 12 || d100 > 14)) return `${n} дня`;
  return `${n} дней`;
}

// Подписи, написанные руками там, где у направления есть свой сюжет. Всё остальное
// считается из чисел — ниже. Числа сюда не кладём.
const РУЧНЫЕ = {
  oman: {
    title: 'Летом страна расходится надвое',
    band: { from: 5.5, to: 8.5, label: 'хариф' },
    caption:
      'Зимой обе половины страны живут одинаково. В июле в Маскате 37 °C, ' +
      'а в Салале 28 °C и семь дождливых дней — её накрывает муссон: ' +
      'облака, туман и морось с середины июня до середины сентября.',
  },
};

const round = (v) => Math.round(v);
const пик = (a) => a.indexOf(Math.max(...a));

function подписи(e) {
  const [a, b] = e.cities;
  const rc = e.cities[e.rainOf ?? 0];
  const rp = пик(rc.rainDays);
  const subtitle = 'Сверху дневная температура, снизу дожди. Ось месяцев общая';
  const дождь = `Дождливее всего — ${МЕС_И[rp]}${b ? `, ${rc.name}` : ''}: ${дней(Math.max(...rc.rainDays))}.`;
  if (!b) {
    return {
      title: `${a.name}: температура и дожди по месяцам`,
      subtitle,
      caption: `Самый тёплый месяц — ${МЕС_И[пик(a.tMax)]}, ${round(Math.max(...a.tMax))} °C, ` +
        `самый прохладный — ${МЕС_И[a.tMax.indexOf(Math.min(...a.tMax))]}, ${round(Math.min(...a.tMax))} °C. ${дождь}`,
    };
  }
  const gaps = a.tMax.map((v, i) => ({ i, d: v - b.tMax[i] }));
  const g = gaps.reduce((x, y) => (Math.abs(y.d) > Math.abs(x.d) ? y : x));
  const near = gaps.reduce((x, y) => (Math.abs(y.d) < Math.abs(x.d) ? y : x));
  const разрыв = Math.abs(round(g.d));
  // Сдвиг сезона дождей — сюжет сильнее разницы в градусах: так устроены Таиланд
  // и Шри-Ланка, где на двух берегах дожди идут в разные месяцы.
  const сдвиг = Math.min(Math.abs(пик(a.rainDays) - пик(b.rainDays)), 12 - Math.abs(пик(a.rainDays) - пик(b.rainDays)));
  // Сдвига пиков мало: у Милана и Венеции пики в разных месяцах, но оба по девять
  // дней — это шум, а не разные календари. Нужен ещё и разрыв в самих числах.
  const контраст = Math.max(...a.rainDays.map((v, i) => Math.abs(v - b.rainDays[i])));
  const дождиВрозь = сдвиг >= 3 && контраст >= 5;
  const врозь = разрыв >= 5 || дождиВрозь;
  // Названия городов не склоняем: «в Пхукет пик» и «в Венеция» — машинная речь.
  const проДожди = дождиВрозь
    ? ` Пик дождей приходится на разные месяцы: ${a.name} — ${МЕС_И[пик(a.rainDays)]} (${дней(Math.max(...a.rainDays))}), ` +
      `${b.name} — ${МЕС_И[пик(b.rainDays)]} (${дней(Math.max(...b.rainDays))}).`
    : ` ${дождь}`;
  return {
    title: врозь ? `${a.name} и ${b.name} живут по разным календарям` : `${a.name} и ${b.name}: год по месяцам`,
    subtitle,
    caption: (разрыв >= 5
      ? `Сильнее всего разница в ${МЕС_П[g.i]}: ${a.name} ${round(a.tMax[g.i])} °C против ${round(b.tMax[g.i])} °C, ближе всего — в ${МЕС_П[near.i]}.`
      : `По температуре обе точки держат один календарь: сильнее всего расходятся в ${МЕС_П[g.i]}, и то на ${разрыв} °C.`) + проДожди,
  };
}

export const CLIMATE_CHART = Object.fromEntries(
  Object.entries(generated).map(([slug, e]) => [slug, { ...e, ...подписи(e), ...(РУЧНЫЕ[slug] || {}) }]),
);

export function climateChart(slug) {
  return CLIMATE_CHART[slug] || null;
}
