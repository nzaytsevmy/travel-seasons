// Склонение существительного (и глагола) по числительному.
//
// Зачем: счётчики на страницах подставляются из данных и меняются при каждом
// добавлении направления. Захардкоженная форма «41 стран» / «74 направлений»
// читается как сломанный русский — Quality Radar фиксировал это на /seasons/,
// /visa/, /cards/ и в llms.txt с 29.06.2026.
//
// Правило: 1, 21, 31… (кроме 11) → первая форма; 2–4, 22–24… (кроме 12–14) →
// вторая; остальное → третья.
export function plural(n, one, few, many) {
  const abs = Math.abs(Number(n) | 0);
  const m10 = abs % 10;
  const m100 = abs % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}

// Готовые формы для счётчиков, которые встречаются на сайте чаще всего.
// Держим здесь, а не по месту, чтобы одна и та же сущность склонялась одинаково
// на всех страницах.
export const NOUN = {
  // именительный/родительный после числа: «41 направление», «74 направления»
  direction: (n) => plural(n, 'направление', 'направления', 'направлений'),
  country:   (n) => plural(n, 'страна', 'страны', 'стран'),
  post:      (n) => plural(n, 'статья', 'статьи', 'статей'),
  point:     (n) => plural(n, 'точка', 'точки', 'точек'),
  // дательный: «по 41 направлению», «по 74 направлениям»
  directionDat: (n) => plural(n, 'направлению', 'направлениям', 'направлениям'),
  // согласование глагола: «41 направление принимает», «74 принимают»
  accept:    (n) => plural(n, 'принимает', 'принимают', 'принимают'),
  give:      (n) => plural(n, 'даёт', 'дают', 'дают'),
};
