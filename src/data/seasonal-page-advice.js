export function getSeasonalPageAdvice(kind, country, month) {
  const key = kind === 'trips' ? `${kind}/${month}/${country}` : `${kind}/${country}/${month}`;
  const page = pages[key];
  if (!page) return null;
  const action = (item) => {
    if (!item) return null;
    const subId = `seasonal_${kind}_${country}_${month}_${item.id}`;
    const href = item.kind === 'flight'
      ? aviasalesRoute('MOW', item.airport, subId, 10)
      : item.kind === 'hotel'
        ? ostrovokCountry(country, subId)
        : cherehapaCountry(country, subId);
    return { ...item, href };
  };
  return { ...page, sections: page.sections.map((section) => ({ ...section, action: action(section.action), secondAction: action(section.secondAction) })) };
}
